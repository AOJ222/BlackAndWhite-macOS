#!/usr/bin/env python3
"""Write native/app/game-manifest.json: what a complete copy of the game looks like, file by file.

    python3 native/app/make-game-manifest.py --game native/run/game --disc native/run/cd --cab <folder> \
        --game-120 bw-game-1.2 --game-142 toolkit-trial/bw-1.42 \
        --program-dir bw1-decomp/orig/BW1W100

--game is a game folder that is known to work (the staged copy the checks were made with), --disc the
disc image's files (native/bw-native/tools/prepare_disc.py makes it), and --cab the folder made by

    unshield -d <folder> x <disc>/data1.cab

(the installer's cabinets, with unshield's default names: spaces and angle brackets become underscores).
--game-120 and --game-142 are installed copies of the other versions of the game, when they are at hand:
the files a patch changed are written down in every form they are known in, so a copy of any version is
accepted. --program-dir holds the program files the native build was made from (the game program and its
four libraries); they are generated by the app at set-up time, never taken from the player's disc, so only
their sizes and SHA-256 go in, under "program".

Every other file of the game folder is matched to the cabinet or disc file with the same SHA-256 and the
same file name, and written down with its size and hash, so that import-game.py and the app can build the
folder from a disc and check every file they make. Some cabinet files go to two places (Data/ and
Data/Misc/, the Eyes and Intro meshes, ChallengeScroll.raw): both places are listed. The manifest holds
paths, sizes and hashes only, no game data.

Each entry says how it is checked ("check"):
  "strict"  the content must be one of the known forms ("sha256" itself, plus "variants" from the
            other versions);
  "any"     any content is accepted, for the files that carry a language or a patch's own text and
            sound (everything under Data/Audio/, Data/Text/ and Scripts/); the file must be there.
A few files are "optional": a complete copy may not have them (DirectX leftovers of the installer, two
debug libraries, one landscape file a patch removed). Two files are written down with the cabinet's hash
and marked "mutable" (Data/Textures/PlayersSymbols.raw and PlayersSymbolsa.raw): the staged folder's
copies differ from the cabinet's although the sizes are the same, and the native build copies these files
before the game may write to them (src/overlay.cpp), so the game seems to write to them (inferred); a
check therefore allows a different content for them.
"""
import argparse
import hashlib
import json
import os
import sys
from collections import defaultdict
from pathlib import Path

HERE = Path(__file__).resolve().parent
LEFTOVERS = ("MemoryLeaks.txt", "Profiles/")
REWRITTEN = ("Data/Textures/PlayersSymbols.raw", "Data/Textures/PlayersSymbolsa.raw")
INSTALLER_ONLY_GROUPS = (
    "Setup_Program/", "_Engine_", "_Support_", "WorkStuff/", "readme_-_usa/",
)
# The program files are generated by the app at set-up, never taken from the player's copy:
# (where the file sits in the game folder, its name in --program-dir and under "Plug Ins").
PROGRAM = (
    ("runblack.exe", "runblack-decrypted.exe"),
    ("lhlogr.dll", "lhlogr.dll"),
    ("LHaudiodllR.dll", "LHaudiodllR.dll"),
    ("LHMultiplayerR.dll", "LHMultiplayerR.dll"),
    ("Plug Ins/ScriptLibraryR.dll", None),
)
PROGRAM_DESTS = {dest for dest, _src in PROGRAM}
OPTIONAL = {
    "DSETUP.dll",
    "dsetup32.dll",
    "Data/Landscape/dance.lnd",
    "Plug Ins/LanguageD.dll",
    "Plug Ins/ScriptLibraryD.dll",
}
ANY_PREFIXES = ("Data/Audio/", "Data/Text/", "Scripts/")


def check_kind(dest):
    return "any" if dest.startswith(ANY_PREFIXES) else "strict"


def sha256(path):
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for block in iter(lambda: f.read(1 << 20), b""):
            h.update(block)
    return h.hexdigest()


def walk(root):
    for dirpath, _dirs, files in os.walk(root):
        for name in files:
            p = os.path.join(dirpath, name)
            if os.path.islink(p):
                continue
            yield os.path.relpath(p, root).replace(os.sep, "/"), p


def hashed_tree(root):
    if not root:
        return {}
    return {rel: (os.path.getsize(p), sha256(p)) for rel, p in walk(root)}


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--game", required=True)
    ap.add_argument("--disc", required=True)
    ap.add_argument("--cab", required=True)
    ap.add_argument("--game-120")
    ap.add_argument("--game-142")
    ap.add_argument("--program-dir", help="the folder the program files were lifted from")
    ap.add_argument("--out", default=str(HERE / "game-manifest.json"))
    args = ap.parse_args()

    cab = {rel: (p, sha256(p)) for rel, p in walk(args.cab)}
    disc = {}
    for rel, p in walk(args.disc):
        if rel.lower().endswith((".cab", ".hdr")):
            continue  # the cabinets themselves are not game files
        disc[rel] = (p, sha256(p))
    others = {"1.20": hashed_tree(args.game_120), "1.42": hashed_tree(args.game_142)}
    cab_by_hash = defaultdict(list)
    for rel, (_p, h) in cab.items():
        cab_by_hash[h].append(rel)
    disc_by_hash = defaultdict(list)
    for rel, (_p, h) in disc.items():
        disc_by_hash[h].append(rel)

    program = []
    if args.program_dir:
        pdir = Path(args.program_dir)
        for dest, src in PROGRAM:
            p = (pdir / src) if src else (Path(args.game) / dest)
            if not p.is_file():
                print("problem: program file %s is missing" % p, file=sys.stderr)
                return 1
            program.append({"dest": dest, "size": os.path.getsize(p), "sha256": sha256(p)})

    entries = []
    problems = []
    for rel, p in sorted(walk(args.game)):
        if rel in LEFTOVERS or rel.startswith(LEFTOVERS[1]):
            continue
        if rel in PROGRAM_DESTS:
            continue
        if rel in REWRITTEN:
            # the cabinet's own copy, found by name
            src = "Textures/" + rel.rsplit("/", 1)[1]
            if src not in cab:
                problems.append("%s: %s is not in the cabinet" % (rel, src))
                continue
            sp, h = cab[src]
            entries.append({"dest": rel, "size": os.path.getsize(sp), "sha256": h, "from": "cab", "src": src,
                            "mutable": True})
            continue
        h = sha256(p)
        base = rel.rsplit("/", 1)[-1].lower()
        cands = [c for c in cab_by_hash.get(h, []) if c.rsplit("/", 1)[-1].lower() == base
                 and not c.startswith(INSTALLER_ONLY_GROUPS)]
        if cands:
            # several cabinet files can have this content (tattoocols.raw is in two groups): the first by name
            entry = {"dest": rel, "size": os.path.getsize(p), "sha256": h, "from": "cab", "src": sorted(cands)[0]}
        else:
            dc = [c for c in disc_by_hash.get(h, []) if c.rsplit("/", 1)[-1].lower() == base]
            if not dc:
                problems.append("%s: no cabinet or disc file with this content and name" % rel)
                continue
            entry = {"dest": rel, "size": os.path.getsize(p), "sha256": h, "from": "disc", "src": sorted(dc)[0]}
        entry["check"] = check_kind(rel)
        variants = []
        for tree in others.values():
            got = tree.get(rel)
            if got and got[1] != h and got not in variants:
                variants.append(got)
        if variants:
            entry["variants"] = [{"size": s, "sha256": v} for s, v in variants]
        if rel in OPTIONAL:
            entry["optional"] = True
        entries.append(entry)

    if problems:
        for line in problems:
            print("problem:", line, file=sys.stderr)
        return 1
    manifest = {
        "format": 2,
        "about": "What a complete copy of Black & White looks like, file by file: where each file of the "
                 "game folder comes from on the disc ('cab' is a file of the installer's data1.cab/data2.cab, "
                 "with unshield's default names; 'disc' is a loose file of the disc), its size and SHA-256, "
                 "the forms the file is known in from the other versions of the game ('variants'), and how "
                 "it is checked ('strict', or 'any' for the files that carry a language). The five program "
                 "files are under 'program': the app generates them at set-up and never takes them from the "
                 "player's copy, so every version of the disc works. Paths, sizes and hashes only.",
        "disc_label": "BNW",
        "program": program,
        "files": entries,
    }
    with open(args.out, "w") as f:
        json.dump(manifest, f, indent=1)
        f.write("\n")
    by_from = defaultdict(int)
    for e in entries:
        by_from[e["from"]] += 1
    print("wrote %s: %d content files (%s), %d program files"
          % (args.out, len(entries), ", ".join("%s %d" % kv for kv in sorted(by_from.items())), len(program)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
